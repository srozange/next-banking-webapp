-- Documents générés (DOCUMENTS du legacy) : une ligne par client, type et paramètres, créée à la première génération.
-- download_count compte les téléchargements réussis. Aucun now(), CURRENT_TIMESTAMP ni CURRENT_DATE : le temps vient
-- du port Horloge. customer_id est un identifiant numérique de client, sans clé étrangère (autre service).
create table documents (
    id              bigint generated by default as identity primary key,
    customer_id     bigint       not null,
    document_type   varchar(40)  not null,
    filename        varchar(255) not null,
    mime_type       varchar(100) not null,
    file_size_bytes bigint       not null,
    generated_at    timestamptz  not null,
    download_count  integer      not null default 0
                    constraint documents_compteur_positif check (download_count >= 0),
    checksum        varchar(64),
    parametres      varchar(500) not null default ''
);

-- Clé de la ligne à incrémenter : client, type et paramètres (compteId=1 pour le RIB et l'attestation du compte 1).
create unique index documents_par_client_type_parametres on documents (customer_id, document_type, parametres);
