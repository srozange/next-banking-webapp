-- Utilisateurs de Demo Bank (clients, conseillers, administrateur), colonnes du legacy.
-- password : empreinte préfixée de son algorithme ({bcrypt}...), jamais un mot de passe en clair.
create table customers (
    id            bigint generated by default as identity primary key,
    username      varchar(255) not null unique,
    password      varchar(255) not null,
    full_name     varchar(255) not null,
    email         varchar(255) not null,
    phone         varchar(20),
    role          varchar(20)  not null default 'CLIENT'
                  constraint customers_role check (role in ('CLIENT', 'CONSEILLER', 'ADMIN')),
    active        boolean      not null default true,
    advisor_id    bigint       references customers (id),
    advisor_since date
);
