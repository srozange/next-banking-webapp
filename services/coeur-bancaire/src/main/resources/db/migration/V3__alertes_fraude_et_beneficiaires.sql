-- Alertes de fraude (FRAUD_ALERTS du legacy) et bénéficiaires externes (EXTERNAL_BENEFICIARIES, lecture seule ici,
-- gestion en epic 4). Aucun now(), CURRENT_TIMESTAMP ni CURRENT_DATE : le temps vient du port Horloge.
-- Alerte : une ligne par signal levé d'un virement dont le score cumulé dépasse le seuil, statut OPEN à la création.
-- virement_id est absent pour les alertes sans virement (échecs de connexion répétés, story 3.10).
create table alertes_fraude (
    id          bigint generated by default as identity primary key,
    client_id   bigint       not null,
    virement_id bigint       references virements (id),
    regle       varchar(30)  not null
                constraint alertes_fraude_regle check (regle in
                    ('LARGE_AMOUNT', 'HIGH_FREQUENCY', 'NEW_BENEFICIARY', 'UNUSUAL_HOURS', 'ROUND_AMOUNT',
                     'FOREIGN_IBAN', 'RAPID_SUCCESSION', 'VELOCITY_CHECK', 'MULTIPLE_FAILED_AUTH')),
    score       integer      not null
                constraint alertes_fraude_score check (score >= 0),
    description text,
    statut      varchar(20)  not null default 'OPEN'
                constraint alertes_fraude_statut check (statut in ('OPEN', 'CONFIRMED', 'FALSE_POSITIVE', 'REVIEWED')),
    cree_le     timestamptz  not null,
    revu_le     timestamptz,
    revu_par    varchar(100)
);

create index alertes_fraude_par_client on alertes_fraude (client_id, cree_le desc);
create index alertes_fraude_par_virement on alertes_fraude (virement_id);

create table beneficiaires_externes (
    id        bigint generated by default as identity primary key,
    client_id bigint       not null,
    titulaire varchar(255) not null,
    iban      varchar(34)  not null,
    libelle   varchar(255) not null,
    banque    varchar(255),
    bic       varchar(11),
    zone_sepa boolean,
    actif     boolean,
    cree_le   timestamptz
);

create index beneficiaires_externes_par_client on beneficiaires_externes (client_id, iban);

-- Signaux d'historique du contrôle de fraude : virements d'un client par date de soumission.
create index virements_par_client_soumission on virements (client_id, soumis_le desc);
