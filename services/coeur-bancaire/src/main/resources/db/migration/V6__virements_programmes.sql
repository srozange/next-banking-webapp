-- Virements programmés (FEAT-004, story 4.3) : RECURRING_TRANSFERS du legacy. Le bénéficiaire est un compte interne,
-- désigné par son numéro. Aucun now(), CURRENT_TIMESTAMP ni CURRENT_DATE : le temps vient du port Horloge.
-- prochaine_execution : date saisie à 00:00 Europe/Paris ; l'exécution des échéances est livrée par la story 4.6.
create table virements_programmes (
    id                   bigint generated by default as identity primary key,
    client_id            bigint         not null,
    compte_source_id     bigint         not null references comptes (id),
    numero_beneficiaire  varchar(34)    not null,
    libelle_beneficiaire varchar(100)   not null,
    montant              numeric(19, 2) not null
                         constraint virements_programmes_montant_positif check (montant > 0),
    frequence            varchar(20)    not null
                         constraint virements_programmes_frequence check (frequence in
                             ('HEBDOMADAIRE', 'MENSUEL', 'BIMESTRIEL', 'TRIMESTRIEL', 'SEMESTRIEL', 'ANNUEL')),
    motif                varchar(255),
    prochaine_execution  timestamptz    not null,
    actif                boolean        not null,
    nb_executions        integer        not null
                         constraint virements_programmes_executions check (nb_executions >= 0),
    cree_le              timestamptz    not null
);

create index virements_programmes_par_client on virements_programmes (client_id, prochaine_execution, id);
