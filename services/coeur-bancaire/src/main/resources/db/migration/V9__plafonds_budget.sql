-- Plafonds mensuels de dépenses par catégorie (FEAT-006, story 4.12 : lecture du décompte ; l'écriture arrive avec la
-- story 4.13). Un plafond par client, catégorie et mois (AAAA-MM). client_id : identifiant numérique sans clé étrangère.
create table plafonds_budget (
    id        bigint generated by default as identity primary key,
    client_id bigint         not null,
    categorie varchar(20)    not null,
    mois      char(7)        not null,
    plafond   numeric(19, 2) not null,
    constraint plafonds_budget_unique unique (client_id, categorie, mois)
);
