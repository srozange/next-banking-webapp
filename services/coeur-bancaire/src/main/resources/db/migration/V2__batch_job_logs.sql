-- Journal des traitements nocturnes (FEAT-011) : colonnes du legacy BATCH_JOB_LOGS. Cette migration ne l'alimente pas ;
-- la story 4.5 (traitements nocturnes) reprend la table si elle existe.
-- La contrainte sur status est une dette du legacy : elle ne tolère que ces trois valeurs.
create table batch_job_logs (
    id                bigint generated by default as identity primary key,
    job_name          varchar(100) not null,
    start_time        timestamptz,
    end_time          timestamptz,
    records_processed integer,
    status            varchar(20) check (status in ('SUCCESS', 'FAILED', 'PARTIAL')),
    details           varchar(1000)
);

create index batch_job_logs_debut on batch_job_logs (start_time desc nulls last);
