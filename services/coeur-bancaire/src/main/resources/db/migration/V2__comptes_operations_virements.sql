-- Comptes, opérations et virements du cœur bancaire (BANK_ACCOUNTS, TRANSACTIONS, TRANSFERS du legacy), outbox
-- d'audit et idempotence des consommateurs. Aucun now(), CURRENT_TIMESTAMP ni CURRENT_DATE : le temps vient du port
-- Horloge. Les références entre services (client_id) sont des identifiants numériques sans clé étrangère.
create table comptes (
    id        bigint generated by default as identity primary key,
    numero    varchar(34)    not null unique,
    type      varchar(20)    not null
              constraint comptes_type check (type in ('COURANT', 'EPARGNE')),
    solde     numeric(19, 2) not null
              constraint comptes_solde_positif check (solde >= 0),
    client_id bigint         not null
);

create index comptes_par_client on comptes (client_id, id);

-- État du virement (AD-12) : seul EXECUTE est produit par la story 3.1. statut : statut d'affichage, distinct de l'état.
-- cle_idempotence : en-tête Idempotency-Key, unique par client (AR-42).
create table virements (
    id                     bigint generated by default as identity primary key,
    client_id              bigint         not null,
    compte_source_id       bigint         not null references comptes (id),
    compte_destinataire_id bigint         not null references comptes (id),
    montant                numeric(19, 2) not null
                           constraint virements_montant_positif check (montant > 0),
    motif                  varchar(100),
    etat                   varchar(30)    not null
                           constraint virements_etat check (etat in
                               ('EXECUTE', 'SUSPENDU', 'LIBERE', 'REJETE', 'REFUSE_ERREUR_CONTROLE')),
    statut                 varchar(10)    not null
                           constraint virements_statut check (statut in ('SUCCESS', 'PENDING')),
    soumis_le              timestamptz    not null,
    cle_idempotence        varchar(100)
);

create unique index virements_cle_idempotence on virements (client_id, cle_idempotence)
    where cle_idempotence is not null;

create table operations (
    id             bigint generated by default as identity primary key,
    compte_id      bigint         not null references comptes (id),
    type           varchar(10)    not null
                   constraint operations_type check (type in ('DEBIT', 'CREDIT')),
    montant        numeric(19, 2) not null,
    solde_apres    numeric(19, 2) not null,
    description    text           not null,
    date_operation timestamptz    not null,
    virement_id    bigint         references virements (id)
);

create index operations_par_compte on operations (compte_id, date_operation desc, id desc);

-- Outbox d'audit : une ligne par entrée (VIREMENT, TRANSFER_EXECUTED...), écrite dans une transaction indépendante de
-- celle du virement, publiée sur coeur-bancaire.audit.v1 après validation, ou par le relais.
create table outbox_audit (
    id           bigint generated always as identity primary key,
    id_evenement uuid    not null unique,
    topic        text    not null,
    cle          text    not null,
    charge       text    not null,
    publie       boolean not null default false
);

create index outbox_audit_non_publiees on outbox_audit (id) where not publie;

-- Idempotence des consommateurs : un événement déjà présent est ignoré, écrit dans la transaction de son effet.
create table evenements_traites (
    id_evenement uuid        primary key,
    traite_le    timestamptz not null
);
