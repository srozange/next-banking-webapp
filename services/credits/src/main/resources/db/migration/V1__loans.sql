-- Prêts (LOANS du legacy) et échéances (LOAN_REPAYMENTS), colonnes du dictionnaire de données.
-- customer_id : identifiant numérique du client, sans clé étrangère (la table des clients appartient à un autre service).
-- Montants en numeric(19,2) ; taux annuel en pourcentage (4.9000 pour 4,9 %). type et status : valeurs des énumérations du legacy.
create table loans (
    id             bigint generated by default as identity primary key,
    customer_id    bigint         not null,
    type           varchar(20)    not null
                   constraint loans_type check (type in ('IMMOBILIER', 'AUTO', 'CONSOMMATION', 'TRAVAUX', 'ETUDIANT')),
    montant        numeric(19, 2) not null,
    taux_annuel    numeric(7, 4)  not null,
    duree_mois     integer        not null,
    mensualite     numeric(19, 2) not null,
    cout_total     numeric(19, 2) not null,
    total_interets numeric(19, 2) not null,
    motif          varchar(255),
    status         varchar(20)    not null
                   constraint loans_status check (status in ('EN_ATTENTE', 'EN_COURS', 'REMBOURSE', 'REFUSE', 'DEFAUT')),
    date_debut     date           not null,
    date_fin       date           not null
);

create index loans_customer_id on loans (customer_id, date_debut desc);

create table loan_repayments (
    id               bigint generated by default as identity primary key,
    loan_id          bigint         not null references loans (id) on delete cascade,
    numero_echeance  integer        not null,
    date_echeance    date           not null,
    montant_capital  numeric(19, 2) not null,
    montant_interets numeric(19, 2) not null,
    montant_total    numeric(19, 2) not null,
    capital_restant  numeric(19, 2) not null,
    paye             boolean        not null default false,
    date_paiement    timestamptz
);

create index loan_repayments_loan_id on loan_repayments (loan_id, numero_echeance);
