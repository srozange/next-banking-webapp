-- Tables legacy CREDIT_SCORES et RISK_PROFILES (DATA-DICTIONARY.md), possédées par credits (spine) : colonnes du
-- legacy, sans valeur par défaut temporelle (les dates viennent des données ou du port Horloge).
create table credit_scores (
    id                  bigint generated by default as identity primary key,
    customer_id         bigint,
    score               integer        not null,
    category            varchar(20)    not null,
    payment_history_pct integer,
    total_debt          numeric(19, 2),
    credit_age_months   integer,
    calculated_at       timestamptz
);

create index credit_scores_customer_id on credit_scores (customer_id);

create table risk_profiles (
    id               bigint generated by default as identity primary key,
    customer_id      bigint,
    risk_level       varchar(20)    not null,
    patrimoine       numeric(19, 2),
    monthly_income   numeric(19, 2),
    monthly_expenses numeric(19, 2),
    created_at       timestamptz,
    updated_at       timestamptz
);

create index risk_profiles_customer_id on risk_profiles (customer_id);
