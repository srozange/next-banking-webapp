-- Catalogue des produits (FEAT-011) : héritage joint du legacy. bank_products porte les champs communs,
-- une table enfant par type porte les champs propres, jointe sur l'identifiant.
-- Les 13 produits de référence sont hors migrations (reference-data/reference-data.sql).
-- Taux, rendements et LTV sont des fractions décimales à 4 décimales (0.0300 = 3 %), jamais multipliées côté serveur.
create table bank_products (
    id           bigint generated by default as identity primary key,
    product_type varchar(20)   not null check (product_type in ('EPARGNE', 'CREDIT', 'INVESTISSEMENT')),
    active       boolean       not null default true,
    created_at   timestamptz,
    currency     varchar(3),
    description  varchar(500),
    interest_rate numeric(7, 4),
    max_amount   numeric(19, 2),
    min_amount   numeric(19, 2),
    name         varchar(100)  not null
);

create table savings_products (
    id                  bigint primary key references bank_products (id),
    capital_guaranteed  boolean,
    max_duration_months integer,
    min_opening_deposit numeric(19, 2)
);

create table credit_products (
    id                  bigint primary key references bank_products (id),
    max_duration_months integer,
    max_ltv             numeric(7, 4),
    requires_insurance  boolean
);

create table investment_products (
    id              bigint primary key references bank_products (id),
    expected_return numeric(7, 4),
    market_sector   varchar(100),
    risk_level      integer
);

create index bank_products_actifs on bank_products (product_type) where active;
