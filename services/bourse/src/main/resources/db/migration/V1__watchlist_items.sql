-- Watchlist commune à tous les utilisateurs authentifiés (FR-009-10) : aucune colonne d'utilisateur.
-- Les valeurs de référence sont hors migrations (reference-data/reference-data.sql).
create table watchlist_items (
    id       bigint generated by default as identity primary key,
    symbol   varchar(20)  not null,
    name     varchar(100) not null,
    market   varchar(50)  not null,
    currency varchar(10)  not null
);

-- Un symbole n'apparaît qu'une fois, sans tenir compte de la casse (FR-029-09) : garantit le refus d'un doublon
-- même quand deux ajouts se croisent.
create unique index watchlist_items_symbol_unique on watchlist_items (upper(symbol));
